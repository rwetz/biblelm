/** A planet: its metal, day and glyph's origin, and its flask in Splendor Solis. */
const planet = (id: string, title: string, metal: string, day: string, unicode: string, origin: string, see: string[] = []): Curio => ({
  id,
  kind: "symbol",
  family: ["planets", "alchemy"],
  title,
  lede: `${metal}, and ${day}.`,
  mark: id as Curio["mark"],
  unicode,
  data: [
    ["Metal", metal],
    ["Day", day],
    ["The glyph", origin],
  ],
  paintings: [`splendor-solis-${id === "sol" ? "sun" : id === "luna" ? "moon" : id}`],
  see: ["planets", ...see],
  claims: [],
});

const element = (id: string, title: string, drawn: string, signs: string, unicode: string): Curio => ({
  id,
  kind: "symbol",
  family: ["alchemy"],
  title,
  lede: drawn,
  mark: id as Curio["mark"],
  unicode,
  data: [
    ["Drawn", drawn],
    ["Signs of the zodiac", signs],
  ],
  see: ["fire", "air", "water", "earth"].filter((x) => x !== id),
  claims: [],
});

